#!/usr/bin/env python3
"""Trains the word-pair (bigram) model used by MixedDecoder.

The corpus is segmented into McBopomofo phrases (the same vocabulary the input
method chooses from), word pairs are counted, and each pair that occurs more
often than chance gets a bonus:

    bonus(prev, next) = log10(P(next | prev) / P(next))

which the decoder adds to McBopomofo's unigram scores.

Corpus sources (repeatable, mixed in order):
    --hf NAME:CONFIG:CHARS   stream CHARS characters of a Hugging Face dataset
                             (CONFIG may be empty), e.g.
                             wikimedia/wikipedia:20231101.zh:150000000
    --text-file PATH         plain UTF-8 text files

Text is converted to Taiwan Traditional Chinese with OpenCC (s2twp) first.

Requirements: pip install opencc datasets
"""

import argparse
import json
import math
import multiprocessing as mp
import os
import re
import sys
import time
from collections import Counter

SENTENCE_START = "^"
MAX_WORD = 6
UNKNOWN_CHAR_SCORE = -9.0
CJK_RUN = re.compile(r"[㐀-鿿豈-﫿]+")

HEADER = """/**
 * @license
 * Word-pair bonuses for mixed Chinese/English input.
 *
 * Derived from {source} with tools/mixed/train_bigram.py. Wikipedia text is
 * licensed under CC BY-SA 4.0, and so is THIS FILE (the data); see NOTICE.md.
 *
 * {stats}
 *
 * Format: one line per previous word, "prev<TAB>next bonus*100 ...".
 */

// Generated by tools/mixed/train_bigram.py. Do not edit by hand.
"""


def load_vocabulary(webdata_path):
    """Phrase -> best log10 score, from McBopomofo's WebData.ts."""
    src = open(webdata_path, encoding="utf-8").read()
    body = src[src.index("`") + 1 : src.rindex("`")]
    # Undo template-literal escaping (\\ -> \, \" -> ", \` -> `), left to right.
    body = re.sub(r"\\(.)", r"\1", body, flags=re.S)
    data = json.loads(body)
    vocab = {}
    for key, entries in data.items():
        if key.startswith("_"):
            continue
        parts = entries.split(" ")
        for i in range(0, len(parts) - 1, 2):
            value = parts[i]
            if not value or len(value) > MAX_WORD or not CJK_RUN.fullmatch(value):
                continue
            try:
                score = float(parts[i + 1])
            except ValueError:
                continue
            if value not in vocab or score > vocab[value]:
                vocab[value] = score
    return vocab


_vocab = None
_converter = None


def _init_worker(vocab):
    global _vocab, _converter
    _vocab = vocab
    import opencc

    _converter = opencc.OpenCC("s2twp")


def segment(text):
    """Most likely split of a CJK run into dictionary phrases (Viterbi)."""
    n = len(text)
    best = [0.0] + [-math.inf] * n
    back = [0] * (n + 1)
    for i in range(n):
        if best[i] == -math.inf:
            continue
        base = best[i]
        for k in range(1, min(MAX_WORD, n - i) + 1):
            w = text[i : i + k]
            s = _vocab.get(w)
            if s is None:
                if k > 1:
                    continue
                s = UNKNOWN_CHAR_SCORE
            if base + s > best[i + k]:
                best[i + k] = base + s
                back[i + k] = i
    words = []
    j = n
    while j > 0:
        i = back[j]
        words.append(text[i:j])
        j = i
    words.reverse()
    return words


def count_chunk(texts):
    """Counts words and word pairs in a list of documents."""
    unigrams = Counter()
    bigrams = Counter()
    sentences = 0
    chars = 0
    for text in texts:
        text = _converter.convert(text)
        for run in CJK_RUN.findall(text):
            if len(run) < 2:
                continue
            words = segment(run)
            chars += len(run)
            sentences += 1
            prev = SENTENCE_START
            for w in words:
                unigrams[w] += 1
                bigrams[(prev, w)] += 1
                prev = w
    return unigrams, bigrams, sentences, chars


def iter_sources(args):
    """Yields (source name, document iterator, character budget)."""
    for path in args.text_file or []:

        def lines(path=path):
            with open(path, encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if line:
                        yield line

        yield path, lines(), args.max_chars
    for spec in args.hf or []:
        name, config, chars = spec.rsplit(":", 2)
        from datasets import load_dataset

        ds = load_dataset(name, config or None, split="train", streaming=True)
        yield name, (row["text"] for row in ds), int(chars)


def heldout_sentences(text, converter, limit):
    """Clean CJK sentences of moderate length, for evaluation."""
    out = []
    text = converter.convert(text)
    for sent in re.split(r"[。！？\n]", text):
        sent = sent.strip()
        if 6 <= len(sent) <= 30 and CJK_RUN.fullmatch(sent):
            out.append(sent)
            if len(out) >= limit:
                break
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--webdata", default="src/McBopomofo/WebData.ts")
    ap.add_argument("--hf", action="append",
                    help="NAME:CONFIG:CHARS of a Hugging Face dataset")
    ap.add_argument("--text-file", action="append")
    ap.add_argument("--max-chars", type=int, default=150_000_000,
                    help="Budget for each --text-file")
    ap.add_argument("--output", default="src/MixedInput/BigramData.ts")
    ap.add_argument("--heldout", help="Write held-out sentences here")
    ap.add_argument("--heldout-count", type=int, default=2000)
    ap.add_argument("--heldout-every", type=int, default=50,
                    help="Every Nth document is held out (not counted)")
    ap.add_argument("--min-count", type=int, default=3)
    ap.add_argument("--min-bonus", type=float, default=0.2)
    ap.add_argument("--max-bonus", type=float, default=3.0)
    ap.add_argument("--max-pairs", type=int, default=300_000)
    ap.add_argument("--discount", type=float, default=0.5)
    ap.add_argument("--chunk-docs", type=int, default=200)
    ap.add_argument("--workers", type=int, default=os.cpu_count() or 2)
    ap.add_argument("--source", default="Chinese Wikipedia")
    args = ap.parse_args()

    t0 = time.time()
    vocab = load_vocabulary(args.webdata)
    print(f"vocabulary: {len(vocab)} phrases", flush=True)

    import opencc

    converter = opencc.OpenCC("s2twp")
    heldout = []
    unigrams = Counter()
    bigrams = Counter()
    sentences = 0
    chars = 0

    n_sources = len(args.text_file or []) + len(args.hf or [])
    per_source_heldout = max(1, args.heldout_count // max(1, n_sources))

    def chunks():
        nonlocal heldout
        batch = []
        for name, docs, budget in iter_sources(args):
            used = 0
            taken = []
            for idx, doc in enumerate(docs):
                if args.heldout and idx % args.heldout_every == 0:
                    if len(taken) < per_source_heldout:
                        taken += heldout_sentences(
                            doc, converter, per_source_heldout - len(taken)
                        )
                    continue
                batch.append(doc)
                used += len(doc)
                if len(batch) >= args.chunk_docs:
                    yield batch
                    batch = []
                if used >= budget:
                    break
            heldout += taken
            print(f"source {name}: {used / 1e6:.1f}M raw characters, "
                  f"{len(taken)} held-out sentences", flush=True)
        if batch:
            yield batch

    with mp.Pool(args.workers, initializer=_init_worker, initargs=(vocab,)) as pool:
        for i, (u, b, s, c) in enumerate(pool.imap_unordered(count_chunk, chunks())):
            unigrams.update(u)
            bigrams.update(b)
            sentences += s
            chars += c
            if i % 20 == 0:
                print(
                    f"{chars / 1e6:.1f}M chars, {len(bigrams) / 1e6:.2f}M pairs, "
                    f"{time.time() - t0:.0f}s",
                    flush=True,
                )
            if len(bigrams) > 8_000_000:
                # Keep memory bounded: drop pairs seen only once so far.
                bigrams = Counter({k: v for k, v in bigrams.items() if v > 1})

    total = sum(unigrams.values())
    print(f"done counting: {chars} chars, {sentences} sentences, {total} words",
          flush=True)

    # Bonus = log10(P(next|prev) / P(next)), with absolute discounting.
    scored = []
    for (prev, nxt), c in bigrams.items():
        if c < args.min_count or nxt not in vocab:
            continue
        if prev != SENTENCE_START and prev not in vocab:
            continue
        c_prev = sentences if prev == SENTENCE_START else unigrams[prev]
        c_next = unigrams[nxt]
        if c_prev == 0 or c_next == 0:
            continue
        p_cond = (c - args.discount) / c_prev
        p_next = c_next / total
        bonus = math.log10(p_cond / p_next)
        if bonus < args.min_bonus:
            continue
        scored.append((c, prev, nxt, min(bonus, args.max_bonus)))
    scored.sort(reverse=True)
    scored = scored[: args.max_pairs]

    by_prev = {}
    for c, prev, nxt, bonus in scored:
        by_prev.setdefault(prev, []).append((nxt, int(round(bonus * 100))))
    lines = []
    for prev in sorted(by_prev):
        items = sorted(by_prev[prev], key=lambda x: -x[1])
        lines.append(prev + "\t" + " ".join(f"{w} {b}" for w, b in items))
    data = "\n".join(lines)

    stats = (
        f"{len(scored)} pairs from {chars / 1e6:.1f}M characters "
        f"({sentences} sentences)."
    )
    with open(args.output, "w", encoding="utf-8") as f:
        f.write(HEADER.format(source=args.source, stats=stats))
        f.write("export const bigramData: string = " + json.dumps(data, ensure_ascii=False) + ";\n")
    print(f"wrote {args.output}: {stats}", flush=True)

    if args.heldout:
        with open(args.heldout, "w", encoding="utf-8") as f:
            f.write("\n".join(heldout) + "\n")
        print(f"wrote {len(heldout)} held-out sentences to {args.heldout}")
    print(f"total time {time.time() - t0:.0f}s", flush=True)


if __name__ == "__main__":
    main()
    # A streaming dataset may still have a download thread running when we
    # stop reading early; skip interpreter finalization so it cannot abort
    # the process after the outputs are safely written.
    sys.stdout.flush()
    sys.stderr.flush()
    os._exit(0)
