#!/usr/bin/env python3
"""Builds src/MixedInput/EnglishData.ts.

Requirements:
    pip install wordfreq
    npm install an-array-of-english-words   (any folder; pass its path below)

Usage:
    python3 tools/mixed/build_english_data.py \
        --wordlist node_modules/an-array-of-english-words/index.json \
        --output src/MixedInput/EnglishData.ts

Each output line is "word zipf*100". Words that are not in the dictionary word
list get a 1.0 zipf penalty, and must be at least 3 letters and fairly common.
"""

import argparse
import json
import re

from wordfreq import top_n_list, zipf_frequency

# Short words and abbreviations common in Taiwanese office and tech chat,
# kept even when the dictionary word list does not have them.
EXTRA = """
ok okay tv pc ai id app apps wifi iphone ipad email emails covid online youtube
facebook instagram ios android api url usb pdf faq ceo cpu gpu vpn dns sql linux
windows github chrome ui ux qa hr pm am vs etc oh hey hi yes yeah lol omg btw fyi
asap bye thx thanks pls plz ppl gonna wanna kinda dm im i'm don't can't it's i'll
i've that's doesn't didn't won't isn't you're we're they're let's cc pr ip os db
vm ci cd js ts ps gpt ppt vlan ssd hdd wfh tbd kpi okr qc rd cp gg bug bugs log
logs ping demo deploy commit merge push pull repo server backup login logout gmail
line meeting zoom teams slack excel word mac macbook google netflix docker nas ram
eta sop po it vip
""".split()

HEADER = """/**
 * @license
 * English word frequencies for mixed Chinese/English input.
 *
 * Derived from wordfreq (https://github.com/rspeer/wordfreq) by Robyn Speer,
 * whose data is licensed under CC BY-SA 4.0, filtered with the word list from
 * an-array-of-english-words (MIT). THIS FILE (the data) is licensed under
 * CC BY-SA 4.0; see NOTICE.md.
 *
 * Format: one entry per line, "word zipf*100". A penalty of 1.0 zipf has
 * already been applied to words that are not in the dictionary word list.
 */

// Generated by tools/mixed/build_english_data.py. Do not edit by hand.
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--wordlist", required=True)
    ap.add_argument("--output", required=True)
    ap.add_argument("--top", type=int, default=90000)
    args = ap.parse_args()

    dictionary = set(json.load(open(args.wordlist)))
    extra = set(EXTRA)
    entries = {}
    for w in top_n_list("en", args.top):
        if w in entries:
            continue
        if not re.fullmatch(r"[a-z][a-z']*[a-z]|[a-z]", w):
            continue
        if len(w) == 1 and w not in ("a", "i"):
            continue
        z = zipf_frequency(w, "en")
        if z < 2.0:
            continue
        if w in dictionary or w in extra:
            entries[w] = z
        elif len(w) >= 3 and z >= 3.3:
            entries[w] = z - 1.0
    for w in extra:
        z = zipf_frequency(w, "en")
        if z >= 2.0:
            entries[w] = max(entries.get(w, 0), z)

    items = sorted(entries.items(), key=lambda x: -x[1])
    data = "\n".join(f"{w} {int(round(z * 100))}" for w, z in items)
    with open(args.output, "w", encoding="utf-8") as f:
        f.write(HEADER + "export const englishData: string = " + json.dumps(data) + ";\n")
    print(f"{len(items)} words written to {args.output}")


if __name__ == "__main__":
    main()
